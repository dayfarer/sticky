#!/bin/bash
# Embeds the sticky-bridge mod in Sticky: writes Sources/Sticky/ClaudeBridgeMod.swift from
#   mods/.claude-plugin/marketplace.json
#   mods/sticky-bridge/**   (all but tsconfig.json and .claude-plugin/types/, which are only for type checks)
# as Swift raw strings, byte for byte. Run it after every change to the mod.
#   mods/embed.sh           regenerate the Swift file
#   mods/embed.sh --check   exit 1 if the Swift file doesn't match the mod's files (nothing is written)
set -euo pipefail
export LC_ALL=C
cd "$(dirname "$0")"
OUT=../Sources/Sticky/ClaudeBridgeMod.swift
PLUGIN=sticky-bridge

die() { echo "embed.sh: $*" >&2; exit 1; }

# The plugin's files, relative to its folder, in a stable order. Links are refused.
files=()
while IFS= read -r f; do files+=("${f#./}"); done < <(
    cd "$PLUGIN" && find . \( -path ./.claude-plugin/types -o -name .DS_Store \) -prune -o \( -type f -o -type l \) -print | sort)
[ ${#files[@]} -gt 0 ] || die "no files in $PLUGIN"
for f in "${files[@]}"; do [ -L "$PLUGIN/$f" ] && die "$PLUGIN/$f is a link"; done
kept=()
for f in "${files[@]}"; do [ "$f" = tsconfig.json ] || kept+=("$f"); done
files=("${kept[@]}")

# One version everywhere.
version=$(plutil -extract version raw -o - "$PLUGIN/.claude-plugin/plugin.json") || die "no version in plugin.json"
[ "$(plutil -extract plugins.0.version raw -o - .claude-plugin/marketplace.json)" = "$version" ] \
    || die "marketplace.json lists another version than plugin.json ($version)"
grep -q "^const MOD_VERSION = '$version'\$" "$PLUGIN/hooks/register.ts" \
    || die "register.ts MOD_VERSION isn't $version"

# Each file must be UTF-8 text with plain newlines, so a Swift raw string holds it as it is.
check_text() {
    iconv -f UTF-8 -t UTF-8 "$1" >/dev/null 2>&1 || die "$1 isn't UTF-8"
    if LC_ALL=C grep -q $'\r' "$1"; then die "$1 has a carriage return"; fi
    [ "$(tr -d '\000' < "$1" | wc -c)" -eq "$(wc -c < "$1")" ] || die "$1 has a NUL byte"
}

# Swift: #"""<newline>TEXT<newline>"""# is TEXT exactly (the newlines next to the quotes aren't part of it). The
# delimiter gets as many # as it takes for TEXT to hold no `"#…` or `\#…` with that many.
literal() {
    local h='#'
    while grep -qF -e "\"$h" -e "\\$h" "$1"; do h="$h#"; done
    printf '%s"""\n' "$h"
    cat "$1"
    printf '\n"""%s' "$h"
}

# A stamp of the embedded files: paths, sizes and bytes.
digest=$( {
    for f in .claude-plugin/marketplace.json; do printf '%s\n%s\n' "marketplace:$f" "$(wc -c < "$f" | tr -d ' ')"; cat "$f"; done
    for f in "${files[@]}"; do printf '%s\n%s\n' "$f" "$(wc -c < "$PLUGIN/$f" | tr -d ' ')"; cat "$PLUGIN/$f"; done
} | shasum -a 256 | cut -c1-16)

check_text .claude-plugin/marketplace.json
for f in "${files[@]}"; do check_text "$PLUGIN/$f"; done

tmp=$(mktemp "${TMPDIR:-/tmp}/ClaudeBridgeMod.XXXXXX")
trap 'rm -f "$tmp"' EXIT
{
    cat <<EOF
// GENERATED by mods/embed.sh from mods/.claude-plugin/marketplace.json and mods/$PLUGIN/. Don't edit it by hand:
// change the mod there, then run mods/embed.sh (mods/embed.sh --check says whether this file is up to date).
//
// The sticky-bridge mod, embedded as text (Bundle.module crashes in the installed app). Sync with Claude App writes
// these files, byte for byte, into a folder marketplace (ClaudeSync.modDir) and installs the plugin from there.

enum ClaudeBridgeMod {
    /// The plugin's version (its .claude-plugin/plugin.json).
    static let version = "$version"
    /// SHA-256 (first 16 hex digits) of the embedded files' paths, sizes and bytes.
    static let digest = "$digest"
    /// What Sticky remembers it installed: a change rewrites the installed files at the next launch.
    static let stamp = version + "+" + digest

    /// .claude-plugin/marketplace.json of the folder marketplace.
    static let marketplace = $(literal .claude-plugin/marketplace.json)

    /// The plugin folder's files ($PLUGIN/<path>).
    static let files: [(path: String, text: String)] = [
EOF
    for f in "${files[@]}"; do
        printf '        ("%s", %s),\n' "$f" "$(literal "$PLUGIN/$f")"
    done
    cat <<'EOF'
    ]
}
EOF
} > "$tmp"

if [ "${1:-}" = --check ]; then
    if cmp -s "$tmp" "$OUT"; then echo "ClaudeBridgeMod.swift is up to date ($version+$digest)"; exit 0; fi
    echo "ClaudeBridgeMod.swift is out of date: run mods/embed.sh" >&2
    exit 1
fi
mv "$tmp" "$OUT"
trap - EXIT
chmod 644 "$OUT"
echo "wrote $(cd "$(dirname "$OUT")" && pwd)/$(basename "$OUT"): ${#files[@]} files + marketplace.json, $version+$digest"
